  static saveDraftScheduleChecked(draft: DraftSchedule | null): void {
    if (!draft) {
      localStorage.removeItem(STORAGE_KEYS.DRAFT_V2);
      localStorage.removeItem(STORAGE_KEYS.DRAFT_V1);
    } else {
      const fullDraft = {
        version: 2,
        editingScheduleId: draft.editingScheduleId !== undefined ? draft.editingScheduleId : null,
        savedAt: getManilaNowISO(),
        ...draft
      };
      const serialized = JSON.stringify(fullDraft);
      localStorage.setItem(STORAGE_KEYS.DRAFT_V2, serialized);
      const verified = localStorage.getItem(STORAGE_KEYS.DRAFT_V2);
      if (verified === null) throw new Error('Persistence verification failed for draft schedule');
    }
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('wwcf:draft-updated', { detail: draft }));
      if (this.getIncludeDraftInCloudBackup()) {
        window.dispatchEvent(new CustomEvent('wwcf:data-changed', { detail: { type: 'draft' } }));
      }
    }
  }

