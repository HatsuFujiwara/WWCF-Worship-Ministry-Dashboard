  static getSchedulesSync(): Schedule[] {
    try {
      const data = localStorage.getItem(STORAGE_KEYS.SCHEDULES);
      if (data === null) {
        return sanitizeSchedules(DEFAULT_SCHEDULES);
      }
      const raw: unknown = JSON.parse(data);
      if (!Array.isArray(raw)) {
        quarantineCorruptStorage(STORAGE_KEYS.SCHEDULES, data, 'Stored schedules data is corrupted (not an array).');
        return [];
      }
      let sanitized = sanitizeSchedules(raw as Schedule[]);
      if (sanitized.length < raw.length) {
        quarantineCorruptStorage(
          STORAGE_KEYS.SCHEDULES,
          data,
          `Skipped ${raw.length - sanitized.length} malformed schedule record(s) while preserving valid lineups.`
        );
      }

      // Auto-sync with authoritative songs database
      try {
        const songData = localStorage.getItem('wwcf_songs_v1');
        if (songData) {
          const songs = JSON.parse(songData);
          if (Array.isArray(songs) && songs.length > 0) {
            const { updatedSchedules, hasChanges } = syncSchedulesWithAuthoritativeSongs(sanitized, songs);
            if (hasChanges) {
              sanitized = updatedSchedules;
              if (sanitized.length === raw.length) {
                localStorage.setItem(STORAGE_KEYS.SCHEDULES, JSON.stringify(sanitized));
              }
            }
          }
        }
      } catch {
        // Fallback gracefully
      }

      if (sanitized.length === raw.length && JSON.stringify(raw) !== JSON.stringify(sanitized)) {
        try {
          localStorage.setItem(STORAGE_KEYS.SCHEDULES, JSON.stringify(sanitized));
        } catch {}
      }
      return sanitized;
    } catch (e) {
      try {
        const raw = localStorage.getItem(STORAGE_KEYS.SCHEDULES);
        if (raw) {
          quarantineCorruptStorage(STORAGE_KEYS.SCHEDULES, raw, 'Stored schedules JSON could not be parsed.');
        }
      } catch {}
      console.error('[StorageService] Failed to read schedules:', e);
      return [];
    }
  }

