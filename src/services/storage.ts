  static applyAppearanceToDOM(params?: {
    isDarkMode?: boolean;
    amoledEnabled?: boolean;
    glassModeEnabled?: boolean;
    performanceMode?: boolean;
  }): EffectiveAppearanceState {
    const effective = this.computeEffectiveAppearance(params);
    if (typeof document !== 'undefined') {
      const root = document.documentElement;
      root.classList.toggle('dark', effective.isDarkMode);
      root.classList.toggle('amoled', effective.amoledEffective);
      root.classList.toggle('glass-mode', effective.glassModeEffective);
      root.setAttribute(
        'data-theme',
        effective.isDarkMode ? (effective.amoledEffective ? 'amoled' : 'dark') : 'light'
      );
      root.setAttribute('data-amoled', effective.amoledEffective ? 'true' : 'false');
      root.setAttribute('data-glass-mode', effective.glassModeEffective ? 'true' : 'false');
      if (document.body) {
        document.body.classList.toggle('dark', effective.isDarkMode);
      }
    }
    return effective;
  }

