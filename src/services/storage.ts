  /**
   * Retrieves whether draft schedule should be included in cloud backup.
   * Scoped per authenticated Google Account. Default is strictly FALSE.
   */
  static getIncludeDraftInCloudBackup(accountKey?: string): boolean {
    if (typeof localStorage === 'undefined') return false;
    const acct = resolveAccountKey(accountKey);
    if (!acct) return false;
    try {
      return localStorage.getItem(`${STORAGE_KEYS.CLOUD_INCLUDE_DRAFT}_${acct}`) === 'true';
    } catch {
      return false;
    }
  }

  static setIncludeDraftInCloudBackup(enabled: boolean, accountKey?: string): void {
    if (typeof localStorage === 'undefined') return;
    const acct = resolveAccountKey(accountKey);
    if (!acct) return;
    try {
      localStorage.setItem(`${STORAGE_KEYS.CLOUD_INCLUDE_DRAFT}_${acct}`, enabled ? 'true' : 'false');
      if (typeof window !== 'undefined') {
        window.dispatchEvent(new CustomEvent('wwcf:draft-cloud-setting-changed', { detail: { enabled, accountKey: acct } }));
        if (enabled && this.hasUnsavedDraftSchedule()) {
          window.dispatchEvent(new CustomEvent('wwcf:data-changed', { detail: { type: 'draft' } }));
        }
      }
    } catch (e) {
      console.error('Failed to save draft cloud backup setting', e);
    }
  }

