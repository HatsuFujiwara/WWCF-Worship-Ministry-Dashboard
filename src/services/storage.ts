export function computeEffectiveAppearance(params: {
  isDarkMode: boolean;
  amoledEnabled: boolean;
  glassModeEnabled: boolean;
  performanceMode: boolean;
}): EffectiveAppearanceState {
  const isDarkMode = Boolean(params.isDarkMode);
  const amoledEnabled = Boolean(params.amoledEnabled);
  const amoledEffective = isDarkMode && amoledEnabled;
  const glassModePreference = Boolean(params.glassModeEnabled);
  const performanceMode = Boolean(params.performanceMode);
  const glassBlockedByPerformance = performanceMode;
  const glassModeEffective = glassModePreference && !performanceMode;

  return {
    isDarkMode,
    amoledEnabled,
    amoledEffective,
    glassModePreference,
    glassModeEffective,
    glassBlockedByPerformance,
    performanceMode
  };
}

// Legacy starter template seed IDs (exact IDs generated by early scaffold)
const LEGACY_SEED_MEMBER_IDS = new Set(['m1', 'm2', 'm3', 'm4', 'm5', 'm6', 'm7', 'm8']);

export function quarantineCorruptStorage(key: string, rawValue: string, reason: string): void {
  if (typeof localStorage === 'undefined') return;
  try {
    localStorage.setItem(
      `wwcf_quarantine_${key}`,
      JSON.stringify({
        quarantinedAt: new Date().toISOString(),
        reason,
        rawValue: rawValue.slice(0, 500000)
      })
    );
  } catch {
    // Non-fatal if storage quota is full
  }
  if (typeof window !== 'undefined') {
    window.dispatchEvent(
      new CustomEvent('wwcf:storage-warning', {
        detail: { key, reason }
      })
    );
  }
}

export function sanitizeMembers(members: Member[]): Member[] {
  if (!Array.isArray(members)) return [];
  const validObjects = members.filter(
    (m): m is Member => Boolean(m && typeof m === 'object' && !Array.isArray(m) && typeof m.name === 'string' && m.name.trim())
  );
  // Only filter out exact legacy seed IDs. Real members sharing common names (e.g. John Reyes, Mark Cruz)
  // are fully preserved with their unique IDs and records.
  const nonDemoMembers = validObjects.filter(
    (m) => !LEGACY_SEED_MEMBER_IDS.has(m.id)
  );

  return nonDemoMembers.map((m, idx) => {
    const rawLabels = Array.isArray(m.labels) ? m.labels : [];
    const updatedLabels = rawLabels
      .filter((lbl): lbl is string => typeof lbl === 'string' && lbl.trim().length > 0)
      .map((lbl) => {
        if (lbl === 'Multimedia') return 'Lyricist';
        if (lbl === 'Song Lead') return 'Song Leader';
        return lbl;
      })
      .filter((lbl) => lbl !== 'Youth' && lbl !== 'Adult');
    return {
      ...m,
      id: typeof m.id === 'string' && m.id.trim() ? m.id : `m_recovered_${idx}`,
      labels: sortTags(updatedLabels)
    };
  });
}

export function sanitizeLabels(labelsList: string[]): string[] {
  if (!Array.isArray(labelsList)) return sortTags([...DEFAULT_LABELS]);
  const mapped = labelsList
    .filter((lbl): lbl is string => typeof lbl === 'string' && lbl.trim().length > 0)
    .map((lbl) => {
      if (lbl === 'Multimedia') return 'Lyricist';
      if (lbl === 'Song Lead') return 'Song Leader';
      return lbl;
    })
    .filter((lbl) => lbl !== 'Youth' && lbl !== 'Adult');
  DEFAULT_LABELS.forEach((defLabel) => {
    if (!mapped.includes(defLabel)) {
      mapped.push(defLabel);
    }
  });
  return sortTags(mapped);
}

export function sanitizeSchedules(schedules: Schedule[]): Schedule[] {
  if (!Array.isArray(schedules)) return [];
  const validObjects = schedules.filter(
    (sch): sch is Schedule =>
      Boolean(sch && typeof sch === 'object' && !Array.isArray(sch) && typeof sch.serviceDate === 'string')
  );
  const nonDemoSchedules = validObjects.filter((sch) => sch.id !== 'sch_sample_1');

  return nonDemoSchedules.map((sch) => {
    const validId = sch.id && sch.id.trim() !== '' ? sch.id : `sch_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;
    const updatedAssignments = (Array.isArray(sch.ministryAssignments) ? sch.ministryAssignments : [])
      .filter((assignment) => Boolean(assignment && typeof assignment === 'object'))
      .map((assignment) => {
        let role = typeof assignment.role === 'string' ? assignment.role : 'Ministry Role';
        if (role === 'Song Lead') role = 'Song Leader';
        if (role === 'Multimedia') role = 'Lyricist';

        // Preserve all valid member assignments - never strip real assignments based on display name!
        const preservedAssigned = (Array.isArray(assignment.assignedMembers) ? assignment.assignedMembers : []).filter(
          (am) => am && typeof am === 'object' && !LEGACY_SEED_MEMBER_IDS.has(am.memberId)
        );

        return {
          ...assignment,
          role,
          assignedMembers: preservedAssigned
        };
      });
    const { noServiceReason: rawNoServiceReason, ...restSch } = sch;
    const cleanNoServiceReason =
      sch.noService === true && typeof rawNoServiceReason === 'string' && rawNoServiceReason.trim()
        ? rawNoServiceReason.trim()
        : undefined;
    return {
      ...restSch,
      id: validId,
      ...(cleanNoServiceReason ? { noServiceReason: cleanNoServiceReason } : {}),
      ministryAssignments: updatedAssignments
    };
  });
}

function resolveAccountKey(accountKey?: string): string | null {
  if (accountKey && accountKey.trim()) {
    return accountKey.trim().toLowerCase().replace(/[^a-z0-9]/g, '_');
  }
  if (typeof localStorage === 'undefined') return null;
  const sub = localStorage.getItem('wwcf_google_user_sub_v1');
  if (sub && sub.trim()) {
    return sub.trim().toLowerCase().replace(/[^a-z0-9]/g, '_');
  }
  const email = localStorage.getItem('wwcf_google_user_email_v1');
  if (email && email.trim()) {
    return email.trim().toLowerCase().replace(/[^a-z0-9]/g, '_');
  }
  return null;
}

