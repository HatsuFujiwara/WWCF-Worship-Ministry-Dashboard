  static saveMembersChecked(members: Member[]): void {
    const sanitized = sanitizeMembers(members);
    const serialized = JSON.stringify(sanitized);
    localStorage.setItem(STORAGE_KEYS.MEMBERS, serialized);
    const verified = localStorage.getItem(STORAGE_KEYS.MEMBERS);
    if (verified === null) throw new Error('Persistence verification failed for members collection');
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('wwcf:members-updated', { detail: sanitized }));
      window.dispatchEvent(new CustomEvent('wwcf:data-changed', { detail: { type: 'members' } }));
    }
  }

